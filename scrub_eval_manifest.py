#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any


SCRUB_VERSION = "canonical_masked_scrubbed_v1"

SOURCE_LEAK_PATTERNS = [
    r"\bQwen\b",
    r"\bGemma\b",
    r"\bprogrammatic\b",
    r"\bsource\b",
    r"\bsource_model\b",
    r"\bgenerated by\b",
    r"\bfixture\b",
    r"\bprovenance\b",
    r"\bmodel\b",
]

RESIDUAL_PATTERNS = [
    r"\bCite:",
    r"\bCitations:",
    r"\bsignal_id\b",
    r"\bload\.last7\b",
    r"\breadiness status\b",
    r"\bcurrent readiness\b",
]


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows = []
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")


def count_patterns(text: str, patterns: list[str]) -> dict[str, int]:
    return {
        pat: len(re.findall(pat, text, flags=re.IGNORECASE))
        for pat in patterns
    }


def truncate_clean(text: str, limit: int) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= limit:
        return text
    cut = text[: limit + 1]
    if " " in cut:
        cut = cut.rsplit(" ", 1)[0]
    return cut.rstrip(" .,:;") + "."


def scrub_text(text: str, *, field_name: str) -> str:
    original = text

    # Remove citation/signal payloads and everything after them in a day summary.
    # These are not source labels, but they are provenance/data-style artifacts.
    text = re.split(
        r"\b(?:Cite|Citations)\s*:",
        text,
        maxsplit=1,
        flags=re.IGNORECASE,
    )[0]

    text = re.split(
        r"\bsignal_id\b",
        text,
        maxsplit=1,
        flags=re.IGNORECASE,
    )[0]

    text = re.split(
        r"\bload\.last7\b",
        text,
        maxsplit=1,
        flags=re.IGNORECASE,
    )[0]

    # Neutralize readiness wording that sounds like internal fixture/provenance language.
    text = re.sub(
        r"\bcurrent readiness status\b",
        "current status",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        r"\breadiness status\b",
        "status",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        r"\bcurrent readiness\b",
        "current status",
        text,
        flags=re.IGNORECASE,
    )

    # Remove dangling punctuation after splits.
    text = re.sub(r"\s+", " ", text).strip()
    text = text.rstrip(" -–—:;,")
    text = re.sub(r"\s+\.", ".", text)

    # Conservative length caps. These reduce presentation imbalance without
    # changing structural fields or day labels.
    if field_name == "purpose_summary":
        text = truncate_clean(text, 120)
    elif field_name == "workout_summary":
        text = truncate_clean(text, 180)
    else:
        text = truncate_clean(text, 180)

    if not text:
        # Avoid empty summaries if a field was only citation residue.
        return "Summary unavailable after source-neutral masking."

    return text


def scrub_obj(obj: Any, *, counters: Counter) -> Any:
    if isinstance(obj, dict):
        out = {}
        for key, value in obj.items():
            if key in {"purpose_summary", "workout_summary"} and isinstance(value, str):
                before = value
                after = scrub_text(value, field_name=key)
                if after != before:
                    counters[f"changed_{key}"] += 1
                out[key] = after
            else:
                out[key] = scrub_obj(value, counters=counters)
        return out

    if isinstance(obj, list):
        return [scrub_obj(x, counters=counters) for x in obj]

    return obj


def manifest_input_path(row: dict[str, Any], manifest_dir: Path, repo_root: Path) -> Path:
    raw = (
        row.get("judge_input_path")
        or row.get("judge_input_file")
        or row.get("input_path")
    )
    if not raw:
        raise ValueError(f"Manifest row missing judge input path: {row}")

    p = Path(raw)
    if p.is_absolute():
        return p

    candidates = [
        repo_root / p,
        manifest_dir / p,
        manifest_dir / "judge_inputs" / p.name,
    ]
    for c in candidates:
        if c.exists():
            return c

    raise FileNotFoundError(f"Could not resolve judge input path {raw!r}")


def compact_counts(rows: list[dict[str, Any]]) -> dict[str, Any]:
    by_judge = Counter(str(r.get("judge_model") or r.get("judge_name") or "") for r in rows)
    by_order = Counter(str(r.get("order") or "") for r in rows)
    by_run = Counter(str(r.get("run_index") if r.get("run_index") is not None else r.get("run") or "") for r in rows)
    by_view = Counter(str(r.get("judge_view") or "") for r in rows)
    pairs = {str(r.get("pair_id")) for r in rows}
    return {
        "n_records": len(rows),
        "n_pairs": len(pairs),
        "by_judge": dict(sorted(by_judge.items())),
        "by_order": dict(sorted(by_order.items())),
        "by_run": dict(sorted(by_run.items())),
        "by_judge_view": dict(sorted(by_view.items())),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--manifest",
        type=Path,
        default=Path("artifacts/gen_src_t070_exp_t000/matching_pool/eval_manifest/pairwise_eval_manifest.jsonl"),
    )
    ap.add_argument(
        "--output-dir",
        type=Path,
        default=Path("artifacts/gen_src_t070_exp_t000/matching_pool/eval_manifest_scrubbed_v1"),
    )
    args = ap.parse_args()

    repo_root = Path.cwd()
    manifest_path = args.manifest
    manifest_dir = manifest_path.parent
    out_dir = args.output_dir
    out_inputs = out_dir / "judge_inputs"
    out_manifest = out_dir / "pairwise_eval_manifest.jsonl"
    out_audit = out_dir / "scrub_audit.json"

    rows = load_jsonl(manifest_path)

    new_rows: list[dict[str, Any]] = []
    counters: Counter = Counter()
    before_residual = Counter()
    after_residual = Counter()
    before_source = Counter()
    after_source = Counter()

    for i, row in enumerate(rows):
        old_input = manifest_input_path(row, manifest_dir, repo_root)
        payload = json.loads(old_input.read_text(encoding="utf-8"))

        before_text = json.dumps(payload, ensure_ascii=False)
        for pat, n in count_patterns(before_text, RESIDUAL_PATTERNS).items():
            before_residual[pat] += n
        for pat, n in count_patterns(before_text, SOURCE_LEAK_PATTERNS).items():
            before_source[pat] += n

        scrubbed = scrub_obj(payload, counters=counters)

        after_text = json.dumps(scrubbed, ensure_ascii=False)
        for pat, n in count_patterns(after_text, RESIDUAL_PATTERNS).items():
            after_residual[pat] += n
        for pat, n in count_patterns(after_text, SOURCE_LEAK_PATTERNS).items():
            after_source[pat] += n

        new_input = out_inputs / old_input.name
        new_input.parent.mkdir(parents=True, exist_ok=True)
        new_input.write_text(
            json.dumps(scrubbed, indent=2, ensure_ascii=False, sort_keys=True),
            encoding="utf-8",
        )

        new_row = dict(row)
        # Keep judge_view as canonical_masked for compatibility with existing gates.
        new_row["judge_view"] = "canonical_masked"
        new_row["canonical_masking_version"] = SCRUB_VERSION
        new_row["judge_input_path"] = str(new_input)
        new_rows.append(new_row)

    write_jsonl(out_manifest, new_rows)

    audit = {
        "scrub_version": SCRUB_VERSION,
        "input_manifest": str(manifest_path),
        "output_manifest": str(out_manifest),
        "output_judge_inputs": str(out_inputs),
        "before_counts": compact_counts(rows),
        "after_counts": compact_counts(new_rows),
        "changed_fields": dict(sorted(counters.items())),
        "residual_patterns_before": dict(sorted(before_residual.items())),
        "residual_patterns_after": dict(sorted(after_residual.items())),
        "source_leak_patterns_before": dict(sorted(before_source.items())),
        "source_leak_patterns_after": dict(sorted(after_source.items())),
        "exact_10000_gate_passed": len(new_rows) == 10000,
        "masking_gate_passed": all(v == 0 for v in after_source.values()) and all(v == 0 for v in after_residual.values()),
        "notes": [
            "Only judge-facing text summaries are edited.",
            "Structural fields, pair ids, judge ids, run indices, order, and source-family metadata are preserved in the manifest.",
            "Original eval_manifest directory is not modified.",
        ],
    }

    out_audit.parent.mkdir(parents=True, exist_ok=True)
    out_audit.write_text(json.dumps(audit, indent=2, ensure_ascii=False, sort_keys=True), encoding="utf-8")

    print(json.dumps(audit, indent=2, ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
